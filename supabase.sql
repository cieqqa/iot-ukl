create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  temp real not null,
  hum real not null,
  gas integer not null,
  soil integer not null
);

create index if not exists sensor_readings_created_at_desc_idx
  on public.sensor_readings (created_at desc);

alter table public.sensor_readings enable row level security;

create table if not exists public.dataset_kematangan (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  source_no integer not null unique,
  suhu_c real not null,
  kelembapan_pct real not null,
  gas_mq3_alkohol_ppm real not null,
  gas_mq135_udara_ppm real not null,
  ph_estimasi real not null,
  kematangan text not null
);

alter table public.dataset_kematangan enable row level security;
