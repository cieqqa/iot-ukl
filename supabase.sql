create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  temp real not null,
  hum real not null,
  gas integer not null,
  soil integer not null
);

create index if not exists sensor_readings_created_at_desc_idx
  on public.sensor_readings (created_at desc);

alter table public.sensor_readings enable row level security;

create table if not exists public.prediction_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  temp real not null,
  hum real not null,
  gas integer not null,
  label text not null,
  confidence real not null,
  recommendation text not null,
  sample_count integer not null
);

create index if not exists prediction_logs_created_at_desc_idx
  on public.prediction_logs (created_at desc);

alter table public.prediction_logs enable row level security;
